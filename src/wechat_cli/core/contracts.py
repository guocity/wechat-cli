"""The small native boundary implemented by each validated WeChat backend."""

from typing import Any, Protocol

Result = dict[str, Any]


class WeChatBackend(Protocol):
    name: str

    def connect(self) -> None: ...
    def close(self) -> None: ...
    def is_alive(self) -> bool: ...
    @property
    def stop_reason(self) -> str | None: ...
    def capabilities(self) -> Result: ...
    def status(self) -> Result: ...
    def self_id(self) -> str | None: ...
    def chats(self) -> Result: ...
    def messages(self, chat_id: str, limit: int) -> Result: ...
    def prepare_text(self, chat_id: str, text: str) -> Result: ...
    def send(self, chat_id: str, text: str) -> Result: ...
    def send_voice(self, prepared: Result) -> Result: ...
    def send_file(self, payload: Result) -> Result: ...
    def post_moment(self, payload: Result) -> Result: ...
    def compose_moment(self, payload: Result) -> Result: ...
    def moment_action(self, session_id: str, action: str) -> Result: ...
    def attachment_data(self, chat_id: str, identifier: str) -> Result: ...
    def voice_data(self, chat_id: str, identifier: str) -> Result: ...
    def cached_media(self, value: str) -> Result: ...
    def transcription_result(self, chat_id: str, identifier: str) -> Result: ...
    def transcribe_voice(self, chat_id: str, identifier: str) -> Result: ...
    def extract_image_text(self, data: str) -> Result: ...
    def controls_status(self) -> Result: ...
    def download_attachment(self, chat_id: str, identifier: str) -> Result: ...
